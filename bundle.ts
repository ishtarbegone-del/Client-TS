type BunOutput = {
    source: string;
    sourcemap: string;
}

async function bunBuild(entry: string, external: string[] = [], minify = true, drop: string[] = []): Promise<BunOutput> {
    const build = await Bun.build({
        entrypoints: [entry],
        sourcemap: 'external',
        define,
        external,
        minify,
        drop,
    });

    if (!build.success) {
        build.logs.forEach((x: any) => console.log(x));
        process.exit(1);
    }

    return {
        source: await build.outputs[0].text(),
        sourcemap: build.outputs[0].sourcemap ? await build.outputs[0].sourcemap.text() : ''
    };
}

async function applyTerser(script: BunOutput): Promise<boolean> {
    const mini = await minify(script.source, {
        sourceMap: {
            content: script.sourcemap
        },
        toplevel: true,
        // format: {
        //     beautify: true
        // },
        compress: {
            ecma: 2020
        },
        mangle: {
            nth_identifier: nth_identifier,
            properties: {
                reserved: [
                    // stdlib
                    'willReadFrequently',
                    'usedJSHeapSize',

                    // LostCityRef F-keys (GameShell overrides)
                    'stealF12',
                    'stealF10',
                    'stealF9',
                    'stealF7',
                    'stealShiftS',

                    // wasm
                    // must be callable:
                    '_abort_js',
                    'emscripten_resize_heap',
                    'fd_close',
                    'fd_seek',
                    'fd_write',
                    // must be an object:
                    'env',
                    'wasi_snapshot_preview1',
                    // is not an object:
                    'instance',
                    // is not a function:
                    'emscripten_stack_init',
                    'emscripten_stack_get_end',
                    '__wasm_call_ctors',
                    // imports:
                    'HEAPU8',
                    '_malloc',
                    '_free',
                    '_realloc',
                    '_BZ2_bzBuffToBuffCompress',
                    '_BZ2_bzBuffToBuffDecompress',
                    '__emscripten_stack_restore',
                    '__emscripten_stack_alloc',
                    '_emscripten_stack_get_current',
                    'memory',
                    '__indirect_function_table',
                    'wasmMemory',
                    '_tsf_load_memory',
                    '_tsf_close',
                    '_tsf_reset',
                    '_tsf_set_output',
                    '_tsf_channel_set_bank_preset',
                    '_tml_load_memory',
                    '_midi_render',
                    // exports:
                    '_emscripten_stack_restore',
                    '_emscripten_stack_alloc',
                    'emscripten_stack_get_current',
                    'memory',
                    'malloc',
                    'free',
                    'realloc',
                    'tsf_load_memory',
                    'tsf_close',
                    'tsf_reset',
                    'tsf_set_output',
                    'tsf_channel_set_bank_preset',
                    'tml_load_memory',
                    'midi_render',
                    'BZ2_bzBuffToBuffCompress',
                    'BZ2_bzBuffToBuffDecompress',
                    'setValue',
                    'getValue',
                    'calledRun',
                    'exit'
                ]
            }
        }
    });

    script.source = mini.code ?? '';
    script.sourcemap = mini.map?.toString() ?? '';
    return true;
}

